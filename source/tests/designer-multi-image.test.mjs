test('asynchronous batch preserves order, survives invalid files and blocks premature export',async()=>{
 const t=setup(),{api,w,click}=t;click('[data-circle-preset="two-90"]');
 let finishFirst; const firstReady=new Promise(resolve=>finishFirst=resolve);
 const png=new ArrayBuffer(24),bytes=new Uint8Array(png),view=new DataView(png);
 bytes.set([137,80,78,71,13,10,26,10]);bytes.set([73,72,68,82],12);view.setUint32(16,600);view.setUint32(20,600);
 let decoded=0;
 w.Image=class {constructor(){this.naturalWidth=600;this.naturalHeight=600;this.name='decoded-'+(++decoded);}set src(value){queueMicrotask(()=>this.onload());}};
 const file=(name,wait=false)=>({name,type:'image/png',size:24,arrayBuffer:async()=>{if(wait)await firstReady;return png;}});
 const input=w.document.getElementById('imageInput');Object.defineProperty(input,'files',{configurable:true,value:[file('first.png',true),{name:'bad.txt',type:'text/plain',size:3},file('second.png')]});
 input.dispatchEvent(new w.Event('change'));
 assert.equal(input.disabled,true);assert.equal(api.outputIsReady(),false);
 finishFirst();for(let i=0;i<50&&input.disabled;i++)await new Promise(resolve=>setImmediate(resolve));
 assert.equal(input.disabled,false);assert.deepEqual(Array.from(api.state.layers,x=>x.imageName),['first.png','second.png']);
 assert.equal(api.getCircleLayer(0).imageName,'first.png');assert.equal(api.getCircleLayer(1).imageName,'second.png');assert.equal(api.outputIsReady(),true);
 assert.match(w.document.getElementById('fileMeta').textContent,/bad.txt/);
 click('#undoButton');assert.equal(api.state.layers.length,1);assert.equal(api.state.imageName,'first.png');
 click('#undoButton');assert.equal(api.state.layers.length,0);assert.equal(api.outputIsReady(),false);
 t.dom.window.close();
});
